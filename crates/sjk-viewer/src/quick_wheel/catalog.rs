/// The Settings editor's groups of actions, in the order it lists them.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Group {
    Camera,
    Interface,
    Player,
    Emotes,
    Weather,
    Time,
    Server,
}

impl Group {
    pub(crate) const ALL: [Self; 7] = [
        Self::Camera,
        Self::Interface,
        Self::Player,
        Self::Emotes,
        Self::Weather,
        Self::Time,
        Self::Server,
    ];

    /// The group's sub-heading.
    pub(crate) fn label(self) -> &'static str {
        match self {
            Self::Camera => "Camera",
            Self::Interface => "Interface",
            Self::Player => "Player",
            Self::Emotes => "Emotes",
            Self::Weather => "Weather",
            Self::Time => "Time of day",
            Self::Server => "Votes, demos and server",
        }
    }
}

/// One action a wheel choice can run.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct Action {
    /// How `wheel.json` names it; never changes once released.
    pub(crate) id: &'static str,
    /// Its name on the ring, in sentence case.
    pub(crate) label: &'static str,
    /// The console command it runs, exactly as typing it would.
    pub(crate) command: &'static str,
    pub(crate) group: Group,
    pub(crate) state: State,
    /// Its picture in [`ICONS`]; without one the ring shows its name on a disc.
    pub(crate) icon: Option<&'static str>,
}

const fn action(
    id: &'static str,
    label: &'static str,
    command: &'static str,
    group: Group,
    state: State,
    icon: Option<&'static str>,
) -> Action {
    Action {
        id,
        label,
        command,
        group,
        state,
        icon,
    }
}

