/// Index in [`ACTIONS`] of the action `wheel.json` names `id`.
pub(crate) fn action_index(id: &str) -> Option<usize> {
    ACTIONS
        .iter()
        .position(|action| action.id.eq_ignore_ascii_case(id.trim()))
}

