#[cfg(test)]
mod tests {
    use super::*;

    /// Longest action name, in characters: the ring's middle shows it whole.
    const LABEL_CHARS: usize = 16;

    #[test]
    fn every_action_is_named_once_and_its_picture_exists() {
        for (index, action) in ACTIONS.iter().enumerate() {
            assert_eq!(action_index(action.id), Some(index), "{}", action.id);
            assert!(action.label.chars().count() <= LABEL_CHARS, "{}", action.id);
            assert!(action.label.is_ascii() && action.command.is_ascii());
            assert!(!action.command.trim().is_empty());
            if let Some(icon) = action.icon {
                assert!(icon_index(icon).is_some(), "{icon}");
            }
        }
        for id in GENERAL.iter().chain(&WEATHER) {
            assert!(action_index(id).is_some(), "{id}");
        }
        // Every group has something to offer, in the editor's order.
        for group in Group::ALL {
            assert!(
                ACTIONS.iter().any(|action| action.group == group),
                "{group:?}"
            );
        }
        assert_eq!(action_index(" Rain "), Some(10));
        assert_eq!(action_index("hail"), None);
    }

    #[test]
    fn every_icon_is_a_cell_sized_picture() {
        for (name, bytes) in ICONS {
            let icon = image::load_from_memory(bytes).expect(name).into_rgba8();
            assert_eq!(icon.dimensions(), (128, 128), "{name}");
            // Transparent corners: cut out of the board, not a square.
            assert_eq!(icon.get_pixel(0, 0)[3], 0, "{name}");
        }
        assert!(ICONS.len() <= crate::ui_renderer::WHEEL_ICON_CELLS);
        // Every picture is used by an action.
        for (name, _) in ICONS {
            assert!(
                ACTIONS.iter().any(|action| action.icon == Some(name)),
                "{name}"
            );
        }
    }
}
